CREATE TABLE IF NOT EXISTS `dvi_hotel_block_requests` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `itinerary_plan_id` INT NOT NULL,
  `group_type` INT NOT NULL DEFAULT 0,
  `reservation_key` VARCHAR(191) NOT NULL,
  `selection_ids` LONGTEXT NOT NULL,
  `provider` VARCHAR(32) NOT NULL,
  `hotel_id` INT NULL,
  `hotel_code` VARCHAR(100) NULL,
  `hotel_name` VARCHAR(255) NOT NULL,
  `check_in` DATE NULL,
  `check_out` DATE NULL,
  `room_type` TEXT NULL,
  `meal_plan` VARCHAR(100) NULL,
  `room_count` INT NOT NULL DEFAULT 0,
  `occupancy_snapshot` LONGTEXT NULL,
  `request_payload` LONGTEXT NULL,
  `status` VARCHAR(32) NOT NULL DEFAULT 'CONTACT_REQUIRED',
  `contact_email` VARCHAR(320) NULL,
  `contact_phone` VARCHAR(200) NULL,
  `contact_source` VARCHAR(50) NULL,
  `requested_at` DATETIME NULL,
  `responded_at` DATETIME NULL,
  `confirmed_at` DATETIME NULL,
  `cutoff_at` DATETIME NULL,
  `confirmation_reference` VARCHAR(255) NULL,
  `confirmation_channel` VARCHAR(32) NULL,
  `respondent_name` VARCHAR(255) NULL,
  `created_by` INT NULL,
  `responded_by` INT NULL,
  `version` INT NOT NULL DEFAULT 1,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_hotel_block_request_reservation_key` (`reservation_key`),
  KEY `idx_hotel_block_request_plan_group` (`itinerary_plan_id`, `group_type`),
  KEY `idx_hotel_block_request_status` (`status`),
  KEY `idx_hotel_block_request_cutoff` (`cutoff_at`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dvi_hotel_block_events` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `request_id` INT NOT NULL,
  `previous_status` VARCHAR(32) NULL,
  `new_status` VARCHAR(32) NOT NULL,
  `event_type` VARCHAR(50) NOT NULL,
  `actor_type` VARCHAR(32) NOT NULL,
  `actor_id` INT NULL,
  `actor_name` VARCHAR(255) NULL,
  `communication_channel` VARCHAR(32) NULL,
  `notes` TEXT NULL,
  `metadata` LONGTEXT NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_hotel_block_event_request_time` (`request_id`, `created_at`),
  KEY `idx_hotel_block_event_status` (`new_status`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dvi_hotel_block_tokens` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `request_id` INT NOT NULL,
  `token_hash` VARCHAR(64) NOT NULL,
  `expires_at` DATETIME NOT NULL,
  `revoked_at` DATETIME NULL,
  `used_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_hotel_block_token_hash` (`token_hash`),
  KEY `idx_hotel_block_token_request` (`request_id`),
  KEY `idx_hotel_block_token_expiry` (`expires_at`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `dvi_hotel_block_messages` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `request_id` INT NOT NULL,
  `recipient` VARCHAR(320) NULL,
  `delivery_status` VARCHAR(32) NOT NULL DEFAULT 'QUEUED',
  `attempt_count` INT NOT NULL DEFAULT 0,
  `provider_message_id` VARCHAR(255) NULL,
  `last_error` TEXT NULL,
  `sent_at` DATETIME NULL,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_hotel_block_message_request` (`request_id`),
  KEY `idx_hotel_block_message_status` (`delivery_status`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
